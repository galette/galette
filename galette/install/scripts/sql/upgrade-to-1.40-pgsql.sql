-- outgoing webhooks and their deliveries queue
CREATE TABLE galette_webhooks (
  id_webhook integer GENERATED BY DEFAULT AS IDENTITY,
  name character varying(100) NOT NULL,
  url character varying(2048) NOT NULL,
  secret character varying(100) NOT NULL,
  events text NOT NULL,
  access_level smallint NOT NULL DEFAULT 2,
  active boolean NOT NULL DEFAULT TRUE,
  creation_date timestamp NOT NULL,
  modification_date timestamp NOT NULL,
  PRIMARY KEY (id_webhook)
);

CREATE TABLE galette_webhooks_deliveries (
  id_delivery integer GENERATED BY DEFAULT AS IDENTITY,
  id_webhook integer NOT NULL REFERENCES galette_webhooks (id_webhook) ON DELETE CASCADE ON UPDATE CASCADE,
  message_id character varying(64) NOT NULL,
  event_type character varying(100) NOT NULL,
  payload text NOT NULL,
  status smallint NOT NULL DEFAULT 0,
  attempts integer NOT NULL DEFAULT 0,
  next_attempt_at timestamp DEFAULT NULL,
  claimed_at timestamp DEFAULT NULL,
  delivered_at timestamp DEFAULT NULL,
  response_code smallint DEFAULT NULL,
  last_error text,
  creation_date timestamp NOT NULL,
  PRIMARY KEY (id_delivery),
  UNIQUE (id_webhook, message_id)
);
CREATE INDEX galette_webhooks_deliveries_status_idx ON galette_webhooks_deliveries (status, next_attempt_at);
CREATE INDEX galette_webhooks_deliveries_creation_idx ON galette_webhooks_deliveries (creation_date);
