declare(strict_types=1);

namespace Galette\IO;

use Galette\Core\Preferences;
use Analog\Analog;
use Galette\Access\AccessControl;
use Galette\Entity\Group;

/**
 * Groups list PDF
 *
 * @author Johan Cwiklinski <johan@x-tnd.be>
 */

class PdfGroups extends Pdf
{
    public const int SHEET_FONT = self::FONT_SIZE - 2;

    private string $doc_title;

    /**
     * Main constructor, set creator and author
     *
     * @param Preferences   $prefs         Preferences
     * @param AccessControl $accessControl Access control
     */
    public function __construct(Preferences $prefs, private readonly AccessControl $accessControl)
    {
        $this->filename = __('groups_list') . '.pdf';
        parent::__construct($prefs);
    }

    /**
     * Draws page header, repeated on each page
     *
     * @param int $page  Page number, starting at 1
     * @param int $total Total pages
     */
    protected function drawPageHeader(int $page, int $total): void
    {
        $this->text(
            text: _T("Members by groups"),
            h: 10,
            align: 'C',
            valign: 'C',
            x: $this->getLeft(),
            y: 10
        );
    }

    /**
     * Initialize PDF
     */
    public function init(): void
    {
        // Set document information
        $this->doc_title = _T("Members by groups");
        $this->setTitle($this->doc_title);
        $this->setSubject(_T("Generated by Galette"));

        // Set margins
        $this->setPageMargins(10, 25);

        // Set font
        $this->setFont('', self::SHEET_FONT);

        //enable pagination
        $this->showPagination();
    }

    /**
     * Draw file
     *
     * @param array<Group> $groups Groups list
     */
    public function draw(array $groups): void
    {
        $this->PageHeader($this->doc_title);

        $align = $this->i18n->isRTL() ? 'right' : 'left';
        $first = true;
        foreach ($groups as $group) {
            $id = $group->getId();
            if (!$this->accessControl->can('group:export', $group)) {
                Analog::log(
                    'Trying to export group ' . $id . ' as PDF without appropriate permissions',
                    Analog::INFO
                );
                continue;
            }
            // Header
            if ($first === false) {
                $this->ln(5);
            }
            $managers_list = $group->getManagers();
            $managers = [];
            foreach ($managers_list as $m) {
                $managers[] = $m->sfullname;
            }

            //keep heading, managers line and table header row together
            $this->setFont('', self::SHEET_FONT);
            $this->checkPageBreak(4 + (count($managers) > 0 ? 4 : 0) + 3 + 2 * $this->getLineHeight());

            $this->setFont('B', self::SHEET_FONT + 1);
            $this->text(text: $group->getName(), h: 4, align: 'C');
            $this->setFont('', self::SHEET_FONT);

            if (count($managers) > 0) {
                $this->text(
                    text: _T("Managers:") . ' ' . implode(', ', $managers),
                    h: 4,
                    align: $this->i18n->isRTL() ? 'L' : 'R'
                );
            }
            $this->ln(3);

            $rows = [];
            foreach ($group->getMembers() as $m) {
                $rows[] = [
                    '<td style="text-align:' . $align . ';">' . self::escape($m->sname) . '</td>',
                    '<td dir="ltr">' . self::escape($m->email) . '</td>',
                    '<td dir="ltr">' . self::escape($m->phone) . '</td>',
                    '<td dir="ltr">' . self::escape($m->gsm) . '</td>'
                ];
            }
            $html = $this->getHTMLTable(
                ['42%', '26%', '16%', '16%'],
                [
                    '<th>' . self::escape(_T("Name")) . '</th>',
                    '<th>' . self::escape(_T("Email")) . '</th>',
                    '<th>' . self::escape(_T("Phone")) . '</th>',
                    '<th>' . self::escape(_T("GSM")) . '</th>'
                ],
                $rows
            );
            $this->writeHTML($html);
            $first = false;
        }
    }
}
