declare(strict_types=1);

namespace Galette\IO;

use DateTime;
use Galette\Core\Db;
use Galette\Core\Preferences;
use Galette\Entity\Adherent;
use Galette\Entity\PdfModel;
use Safe\DateTimeImmutable;

/**
 * Attendance sheet
 *
 * @author Johan Cwiklinski <johan@x-tnd.be>
 */

class PdfAttendanceSheet extends Pdf
{
    public const int SHEET_FONT = self::FONT_SIZE - 2;
    public const int ATT_SHEET_MODEL = 100;

    public ?string $doc_title = null;
    public ?string $sheet_title = null;
    public ?string $sheet_sub_title = null;
    public ?DateTime $sheet_date = null;
    private bool $wimages = false;

    /**
     * Draws page header, repeated on each page but the first one
     *
     * @param int $page  Page number, starting at 1
     * @param int $total Total pages
     */
    protected function drawPageHeader(int $page, int $total): void
    {
        if ($page > 1) {
            $this->setFont('', self::SHEET_FONT);
            $head_title = $this->doc_title;
            if ($this->sheet_title !== null) {
                $head_title .= ' - ' . $this->sheet_title;
            }
            // No "sheet_sub_title" to prevent long lines
            if ($this->sheet_date !== null) {
                $head_title .= ' - ' . $this->sheet_date->format(__("Y-m-d"));
            }
            $this->text(
                text: $head_title,
                h: 10,
                align: 'C',
                valign: 'C',
                x: $this->getLeft(),
                y: 5
            );
        }
    }

    /**
     * Main constructor, set creator and author
     *
     * @param Db                  $zdb   Database instance
     * @param Preferences         $prefs Preferences
     * @param array<string,mixed> $data  Data to set
     */
    public function __construct(Db $zdb, Preferences $prefs, array $data = [])
    {
        $this->filename = __('attendance_sheet') . '.pdf';
        $class = PdfModel::getTypeClass(self::ATT_SHEET_MODEL);
        $model = new $class($zdb, $prefs);

        // Set document and model information
        $this->doc_title = $data['doc_title'];

        if (isset($data['title']) && trim((string)$data['title']) != '') {
            $this->sheet_title = $data['title'];
            $model->title = $this->sheet_title;
        }
        if (isset($data['subtitle']) && trim((string)$data['subtitle']) != '') {
            $this->sheet_sub_title = $data['subtitle'];
            $model->subtitle = $this->sheet_sub_title;
        }
        if (isset($data['sheet_date']) && trim((string)$data['sheet_date']) != '') {
            $dformat = __("Y-m-d");
            $date = DateTime::createFromFormat(
                $dformat,
                $data['sheet_date']
            );
            $this->sheet_date = $date;
        }

        parent::__construct($prefs, $model);
    }

    /**
     * Initialize PDF
     */
    public function init(): void
    {
        // Set document information
        $this->setTitle($this->doc_title);
        $this->setSubject(_T("Generated by Galette"));
        $this->setKeywords(_T("Attendance sheet"));

        // Leave room for the header repeated on next pages
        $this->setPageMargins(10, 15);

        // Set colors
        $this->setDrawColor('#a0a0a0');
        $this->setTextColor('#000000');
        $this->setFont('', self::SHEET_FONT);

        //enable pagination
        $this->showPagination();
    }

    /**
     * Draw members cards
     *
     * @param array<Adherent> $members Members
     */
    public function drawSheet(array $members): void
    {
        $this->PageHeader($this->doc_title);

        if ($this->sheet_date) {
            $format = __("MMMM, EEEE d y");
            $formatter = new \IntlDateFormatter(
                locale: $this->i18n->getLongID(),
                dateType: \IntlDateFormatter::FULL,
                timeType: \IntlDateFormatter::NONE,
                timezone: \date_default_timezone_get(),
                calendar: \IntlDateFormatter::GREGORIAN,
                pattern: $format
            );
            $datetime = new DateTimeImmutable($this->sheet_date->format('Y-m-d'));
            $date = DateTime::createFromImmutable($datetime);
            $date_fmt = mb_convert_case($formatter->format($date), MB_CASE_TITLE);
            $this->text(text: $date_fmt, h: 7, align: 'C');
        }

        $align = $this->i18n->isRTL() ? 'right' : 'left';
        $widths = $this->wimages ? ['6%', '9%', '43%', '42%'] : ['6%', '52%', '42%'];

        $rows = [];
        $mcount = 0;
        foreach ($members as $m) {
            $mcount++;
            $cells = ['<td style="height:16mm;text-align:right;">' . $mcount . '</td>'];
            if ($this->wimages) {
                $photo = '';
                if ($m->hasPicture()) {
                    // Set photo size to max width or max height 14 mm
                    $ratio = $m->picture->getWidth() / $m->picture->getHeight();
                    $wphoto = $ratio < 1 ? 14 * $ratio : 14;
                    $hphoto = $ratio < 1 ? 14 : 14 / $ratio;
                    $photo = sprintf(
                        '<img src="%1$s" style="width:%2$.2Fmm;height:%3$.2Fmm;"/>',
                        self::getDataUri($m->picture->getPath()),
                        $wphoto,
                        $hphoto
                    );
                }
                $cells[] = '<td style="text-align:center;">' . $photo . '</td>';
            }
            $cells[] = '<td style="text-align:' . $align . ';">' . self::escape($m->sname) . '</td>';
            $cells[] = '<td></td>';
            $rows[] = $cells;
        }

        $html = $this->getHTMLTable(
            widths: $widths,
            headers: [
                '<th colspan="' . (count($widths) - 1) . '">' . self::escape(_T("Name")) . '</th>',
                '<th>' . self::escape(_T("Signature")) . '</th>'
            ],
            rows: $rows,
            border_color: '#a0a0a0',
            row_attrs: 'nobr="true"'
        );
        $this->writeHTML($html);
    }

    /**
     * Add images to file
     */
    public function withImages(): self
    {
        $this->wimages = true;
        return $this;
    }
}
