declare(strict_types=1);

namespace Galette\IO;

use Galette\Core\Preferences;
use Galette\Entity\Adherent;

/**
 * Member labels PDF
 *
 * @author Johan Cwiklinski <johan@x-tnd.be>
 */

class PdfMembersLabels extends Pdf
{
    private int $xorigin;
    private int $yorigin;
    private float $lw;
    private float $lh;
    private float $line_h;

    /**
     * Main constructor, set creator and author
     *
     * @param Preferences $prefs Preferences
     */
    public function __construct(Preferences $prefs)
    {
        $this->setRTL(enable: false);
        $this->filename = __('labels_print_filename') . '.pdf';
        parent::__construct($prefs);
    }

    /**
     * Initialize PDF
     */
    public function init(): void
    {
        // Set document information
        $this->SetTitle(_T("Member's Labels"));
        $this->SetSubject(_T("Generated by Galette"));
        $this->SetKeywords(_T("Labels"));

        // No headers and footers
        $this->setNoHeader();
        $this->setNoFooter();

        // Show full page
        $this->SetDisplayMode('fullpage');

        // Disable Auto Page breaks
        $this->SetAutoPageBreak(auto: false, margin: 0);

        // Set colors
        $this->SetDrawColor(160, 160, 160);
        $this->SetTextColor(0);

        // Set margins
        $this->SetMargins(
            $this->preferences->pref_etiq_marges_h,
            $this->preferences->pref_etiq_marges_v
        );

        // Set font
        //$this->SetFont(self::FONT);

        // Set origin
        // Top left corner
        $this->xorigin = $this->preferences->pref_etiq_marges_h;
        $this->yorigin = $this->preferences->pref_etiq_marges_v;

        // Label width
        $this->lw = round($this->preferences->pref_etiq_hsize);
        // Label heigth
        $this->lh = round($this->preferences->pref_etiq_vsize);
        // Line heigth
        $this->line_h = round($this->lh / 5);
    }

    /**
     * Draw members cards
     *
     * @param array<Adherent> $members Members
     */
    public function drawLabels(array $members): void
    {
        $nb_etiq = 0;
        foreach ($members as $member) {
            // Detect page breaks
            $colsrows = $this->preferences->pref_etiq_cols
                * $this->preferences->pref_etiq_rows;
            if ($nb_etiq % $colsrows == 0) {
                $this->AddPage();
            }
            // Set font
            $this->SetFont(self::FONT, '', $this->preferences->pref_etiq_corps);
            // Set line height ratio
            $this->SetCellHeightRatio(1.35);

            // Compute label position
            $col = $nb_etiq % $this->preferences->pref_etiq_cols;
            $row = (int)($nb_etiq / $this->preferences->pref_etiq_cols)
                % $this->preferences->pref_etiq_rows;
            // Set label origin
            $x = $this->xorigin + $col * (
                round($this->preferences->pref_etiq_hsize)
                + round($this->preferences->pref_etiq_hspace)
            );
            $y = $this->yorigin + $row * (
                round($this->preferences->pref_etiq_vsize)
                + round($this->preferences->pref_etiq_vspace)
            );
            // Draw a frame around the label
            if ($this->preferences->pref_etiq_border) {
                $this->Rect(x: $x, y: $y, w: $this->lw, h: $this->lh);
            }

            $lines = $this->getLabelLines($member);
            // Calculate font size to always display each line inside the frame;
            // company name is not taken into account, it wraps if too long
            $fontsize = $this->preferences->pref_etiq_corps;
            foreach ($lines as $key => $line) {
                if ($key !== 'company') {
                    $this->fixSize($line, $this->preferences->pref_etiq_hsize, $fontsize);
                    $fontsize = (int)$this->getFontSizePt();
                }
            }
            // Reduce font size until full address fits in label height
            $full_address = implode("\n", $lines);
            while ($fontsize > 1 && $this->getStringHeight($this->lw, $full_address) > $this->lh) {
                --$fontsize;
                $this->SetFontSize($fontsize);
            }
            $full_address = nl2br(htmlspecialchars($full_address), use_xhtml: false);
            // Print full address
            $this->writeHTMLCell(
                w: $this->lw,
                h: $this->line_h,
                x: $x,
                y: $y,
                html: $full_address,
                border: 0,
                ln: 0,
                fill: false,
                reseth: true,
                align: 'L',
                autopadding: true
            );

            // Next label
            $nb_etiq++;
        }
    }

    /**
     * Get lines to print on a member label
     *
     * @param Adherent $member Member
     *
     * @return array<string, string>
     */
    public function getLabelLines(Adherent $member): array
    {
        $lines = ['name' => $member->sfullname];
        if ($member->isCompany()) {
            $lines['company'] = trim($member->company_name);
        }
        foreach (explode(PHP_EOL, (string)$member->address) as $i => $address_line) {
            $lines['address_' . $i] = $address_line;
        }
        $lines['town'] = $member->zipcode . ' ' . $member->town;
        $lines['country'] = (string)$member->country;
        return $lines;
    }
}
